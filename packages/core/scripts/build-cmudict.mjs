// Builds packages/core/data/cmudict.txt from a pinned CMU Pronouncing Dictionary
// commit (BSD-2-Clause). Each phone is stored as one ASCII character; the table
// below must match PHONE_CODES in src/ipa/arpabet.ts.
//
// Usage: node packages/core/scripts/build-cmudict.mjs [path/to/cmudict.dict]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const COMMIT = '74790861f652b15e4ac49015a90074ad62a27690';
const SHA256 = '81917843c7f44ce2b094ac63873c2c7a4cf802040792c455ba3ca406891c3d22';
const URL = `https://raw.githubusercontent.com/cmusphinx/cmudict/${COMMIT}/cmudict.dict`;

const VOWELS = 'AA AE AH AO AW AY EH ER EY IH IY OW OY UH UW'.split(' ');
const CONSONANTS = 'B CH D DH F G HH JH K L M N NG P R S SH T TH V W Y Z ZH'.split(' ');
const PHONES = [...VOWELS.flatMap((v) => [`${v}0`, `${v}1`, `${v}2`]), ...CONSONANTS];
const CODE_CHARS = [];
for (let c = 0x21; c <= 0x7e; c++) {
  if (c !== 0x23 && c !== 0x7c) CODE_CHARS.push(String.fromCharCode(c)); // skip # and |
}
const CODE = new Map(PHONES.map((p, i) => [p, CODE_CHARS[i]]));

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../data/cmudict.txt');

const source = process.argv[2]
  ? readFileSync(process.argv[2])
  : Buffer.from(await (await fetch(URL)).arrayBuffer());
const sha = createHash('sha256').update(source).digest('hex');
if (sha !== SHA256) throw new Error(`cmudict.dict sha256 mismatch: ${sha}`);

/** word -> encoded pronunciations, in source order. */
const entries = new Map();
for (const raw of source.toString('utf8').split('\n')) {
  const line = raw.replace(/#.*/, '').trim();
  if (!line) continue;
  const [head, ...phones] = line.split(/\s+/);
  const word = head.replace(/\(\d+\)$/, '');
  const enc = phones
    .map((p) => {
      const ch = CODE.get(p);
      if (!ch) throw new Error(`unknown phone ${p} in ${head}`);
      return ch;
    })
    .join('');
  const list = entries.get(word) ?? [];
  if (!list.includes(enc)) list.push(enc);
  entries.set(word, list);
}

const lines = [
  `# CMU Pronouncing Dictionary ${COMMIT.slice(0, 12)} (BSD-2-Clause). See THIRD_PARTY_NOTICES.md.`,
  '# Generated by packages/core/scripts/build-cmudict.mjs. One char per ARPAbet phone.',
];
for (const word of [...entries.keys()].sort())
  lines.push(`${word}\t${entries.get(word).join('|')}`);
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${entries.size} words to ${out}`);
